#!/usr/bin/env python3
"""Generate a standalone LPDDR4 memory subsystem for simulation with the Winbond W66AP6NB model.

Top level (`lpddr4_top`):
    * LiteDRAM core (DFI injector + controller + crossbar) with one native user port.
    * LPDDR4StrobePHY (JEDEC-accurate pad timing, trained delay lines, DQS-strobed read capture).
    * A 32-bit CSR bus exposing the DFI injector and the PHY training registers, so that the
      testbench can play the role of the LiteX BIOS (initialization and training).
    * LPDDR4 pads, to be connected directly to the DRAM model.

Outputs (in build/standalone_lpddr4/):
    lpddr4_top.v        generated RTL
    lpddr4_csr.svh      CSR addresses (LiteX naming: CSR_<BANK>_<NAME>)
    lpddr4_params.svh   PHY/DRAM parameters and mode register values for the testbench
    sources.f           file list for the simulator (generated RTL + PHY IO macro)
"""

import argparse
from pathlib import Path

from migen import *
from migen.fhdl import verilog

from litex.soc.interconnect import csr_bus

from litedram import modules
from litedram.core import LiteDRAMCore
from litedram.core.controller import ControllerSettings
from litedram.init import get_sdram_phy_init_sequence
from litedram.phy.lpddr4.strobephy import LPDDR4StrobePHY, verilog_sources

# Configuration -----------------------------------------------------------------------------------

SYS_CLK_FREQ  = 100e6           # DRAM clock = 8 x sys = 800 MHz (LPDDR4-1600)
CLOCK_DOMAINS = ["sys", "sys8x", "sys8x_ddr"]

CSR_DATA_WIDTH    = 32
CSR_ADDRESS_WIDTH = 14
CSR_PAGING        = 0x800       # bytes per CSR bank
CSR_MAP           = {"ddrphy": 0, "sdram": 1}

# Top ---------------------------------------------------------------------------------------------

class LPDDR4Standalone(Module):
    def __init__(self):
        # Clocks / reset: clocks come from the testbench (PLL model), one shared reset.
        self.rst = Signal(name="rst")
        for name in CLOCK_DOMAINS:
            cd = ClockDomain(name)
            setattr(self.clock_domains, "cd_" + name, cd)
            self.comb += cd.rst.eq(self.rst)

        # PHY
        self.submodules.ddrphy = phy = LPDDR4StrobePHY(sys_clk_freq=SYS_CLK_FREQ, masked_write=True)

        # DRAM module / core
        self.dram_module = module = modules.W66AP6NB(SYS_CLK_FREQ, "1:8")
        self.submodules.sdram = LiteDRAMCore(
            phy                      = phy,
            geom_settings            = module.geom_settings,
            timing_settings          = module.timing_settings,
            clk_freq                 = SYS_CLK_FREQ,
            controller_settings      = ControllerSettings(with_refresh=True),
            dfii_sw_control_on_reset = True,  # hold RESET_n/CKE low until software initializes the DRAM
        )

        # Native user port
        self.port = self.sdram.crossbar.get_port(mode="both")

        # CSR bus
        self.submodules.csrbankarray = csr_bus.CSRBankArray(self,
            address_map   = lambda name, memory: CSR_MAP.get(name, None),
            data_width    = CSR_DATA_WIDTH,
            address_width = CSR_ADDRESS_WIDTH,
            paging        = CSR_PAGING)
        bus = csr_bus.Interface(data_width=CSR_DATA_WIDTH, address_width=CSR_ADDRESS_WIDTH)
        self.submodules.csrcon = csr_bus.Interconnect(bus, self.csrbankarray.get_buses())

        self.csr_adr   = Signal(CSR_ADDRESS_WIDTH, name="csr_adr")
        self.csr_we    = Signal(name="csr_we")
        self.csr_re    = Signal(name="csr_re")
        self.csr_dat_w = Signal(CSR_DATA_WIDTH, name="csr_dat_w")
        self.csr_dat_r = Signal(CSR_DATA_WIDTH, name="csr_dat_r")
        self.comb += [
            bus.adr.eq(self.csr_adr),
            bus.we.eq(self.csr_we),
            bus.re.eq(self.csr_re),
            bus.dat_w.eq(self.csr_dat_w),
            self.csr_dat_r.eq(bus.dat_r),
        ]

    def get_ios(self):
        ios = {self.rst}
        for name in CLOCK_DOMAINS:
            ios.add(getattr(self, "cd_" + name).clk)
        ios.update(self.port.cmd.flatten())
        ios.update(self.port.wdata.flatten())
        ios.update(self.port.rdata.flatten())
        ios.update({self.csr_adr, self.csr_we, self.csr_re, self.csr_dat_w, self.csr_dat_r})
        ios.update(self.ddrphy.pads.get_ios())
        return ios

# Exports -----------------------------------------------------------------------------------------

def csr_svh(top):
    """CSR word addresses, one localparam per (simple) CSR"""
    shift = (CSR_PAGING // 4).bit_length() - 1
    lines = ["// Auto-generated by standalone_lpddr4/generate.py -- do not edit", ""]
    for name, csrs, mapaddr, rmap in top.csrbankarray.banks:
        lines.append(f"// {name} (bank {mapaddr})")
        index = 0  # word index inside the bank, in the same order as CSRBank.simple_csrs
        for c in csrs:
            nwords = (c.size + CSR_DATA_WIDTH - 1) // CSR_DATA_WIDTH
            addr   = (mapaddr << shift) | index
            ident  = f"CSR_{name}_{c.name}_ADDR".upper()
            lines.append(f"localparam int {ident:<44} = 'h{addr:04x};  // {c.size} bit(s)")
            index += nwords
        assert index == len(rmap.simple_csrs)
        lines.append("")
    return "\n".join(lines)


def params_svh(top):
    phy      = top.ddrphy
    settings = phy.settings
    geom     = top.dram_module.geom_settings
    _, mr    = get_sdram_phy_init_sequence(settings, top.dram_module.timing_settings)

    p = {
        "SYS_CLK_PERIOD_PS": int(round(1e12 / SYS_CLK_FREQ)),
        "NPHASES":           settings.nphases,
        "DATABITS":          settings.databits,
        "NBYTES":            settings.databits // 8,
        "DFI_DATABITS":      settings.dfi_databits,
        "RDPHASE":           settings.rdphase.reset.value,
        "WRPHASE":           settings.wrphase.reset.value,
        "READ_LATENCY":      settings.read_latency,
        "WRITE_LATENCY":     settings.write_latency,
        "CL":                settings.cl,
        "CWL":               settings.cwl,
        "TAP_PS":            phy.tap_ps,
        "TAP_BITS":          phy.tap_bits,
        "NTAPS":             2**phy.tap_bits,
        "GATE_BITS":         7,
        "BANKBITS":          geom.bankbits,
        "ROWBITS":           geom.rowbits,
        "COLBITS":           geom.colbits,
        "NATIVE_ADDR_WIDTH": len(top.port.cmd.addr),
        "NATIVE_DATA_WIDTH": len(top.port.wdata.data),
    }
    lines = ["// Auto-generated by standalone_lpddr4/generate.py -- do not edit", ""]
    lines += [f"localparam int {k} = {v};" for k, v in p.items()]
    lines += ["", "// Mode register values for the operating frequency set point (litedram.init)"]
    lines += [f"localparam logic [7:0] MR{ma}_VALUE = 8'h{op:02x};" for ma, op in sorted(mr.items())]
    lines += ["",
        "// DFII control/command flags (litedram.init)",
        "localparam logic [3:0] DFII_CONTROL_SEL     = 4'h1;",
        "localparam logic [3:0] DFII_CONTROL_CKE     = 4'h2;",
        "localparam logic [3:0] DFII_CONTROL_ODT     = 4'h4;",
        "localparam logic [3:0] DFII_CONTROL_RESET_N = 4'h8;",
        "localparam logic [5:0] DFII_COMMAND_CS      = 6'h01;",
        "localparam logic [5:0] DFII_COMMAND_WE      = 6'h02;",
        "localparam logic [5:0] DFII_COMMAND_CAS     = 6'h04;",
        "localparam logic [5:0] DFII_COMMAND_RAS     = 6'h08;",
        "localparam logic [5:0] DFII_COMMAND_WRDATA  = 6'h10;",
        "localparam logic [5:0] DFII_COMMAND_RDDATA  = 6'h20;",
        "",
    ]
    return "\n".join(lines)

# Main --------------------------------------------------------------------------------------------

def main():
    parser = argparse.ArgumentParser(description="Generate standalone LiteDRAM LPDDR4 subsystem")
    parser.add_argument("--output-dir", default="build/standalone_lpddr4")
    args = parser.parse_args()

    out = Path(args.output_dir)
    out.mkdir(parents=True, exist_ok=True)

    top = LPDDR4Standalone()
    ios = top.get_ios()
    verilog.convert(top, ios=ios, name="lpddr4_top").write(str(out / "lpddr4_top.v"))

    (out / "lpddr4_csr.svh").write_text(csr_svh(top))
    (out / "lpddr4_params.svh").write_text(params_svh(top))
    (out / "sources.f").write_text("\n".join(verilog_sources() + [str((out / "lpddr4_top.v").resolve())]) + "\n")

    s = top.ddrphy.settings
    print(f"Generated {out}/lpddr4_top.v  (CL={s.cl} CWL={s.cwl} read_latency={s.read_latency} "
          f"write_latency={s.write_latency} rdphase={s.rdphase.reset.value} wrphase={s.wrphase.reset.value})")


if __name__ == "__main__":
    main()
